-- Présences : ~80 % de présents, le reste absent ou excusé
insert into public.attendance (training_id, player_id, status)
select t.id, p.id,
  case
    when random() < 0.80 then 'present'
    when random() < 0.50 then 'excused'
    else 'absent'
  end
from public.trainings t
cross join public.players p;

-- Notes des présents (au pas de 0,5, avec une légère progression dans le temps)
insert into public.training_scores
  (training_id, player_id, performance, attitude, seriousness, involvement, comments)
select
  a.training_id,
  a.player_id,
  least(10, round((4 + random() * 4.5 + rn * 0.25) * 2) / 2.0),
  least(5,  round((2.5 + random() * 2.2) * 2) / 2.0),
  least(5,  round((2.5 + random() * 2.2) * 2) / 2.0),
  least(5,  round((2.5 + random() * 2.2) * 2) / 2.0),
  case when random() < 0.25 then 'Bon travail sur les draws, à confirmer.' else null end
from (
  select a.*, dense_rank() over (order by t.date) as rn
  from public.attendance a
  join public.trainings t on t.id = a.training_id
) a
where a.status = 'present';

